import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readMigrationFiles } from "drizzle-orm/migrator";

/**
 * Embeds the committed drizzle-kit migrations in the package as data, so every runtime applies the same statements without reading the filesystem: drizzle's own migrators read the `drizzle/` folder through `node:fs`, which a browser worker does not have.
 *
 * The migrations are parsed by drizzle's own `readMigrationFiles`, so the names, statement splits and hashes are exactly what drizzle's migrators would record. The output is build output, never committed; the `_build` and `_test` scripts run this first.
 */
const root = join(import.meta.dirname, "..");
const migrations = readMigrationFiles({
  migrationsFolder: join(root, "drizzle"),
});
const directory = join(root, "src", "generated");
mkdirSync(directory, { recursive: true });
writeFileSync(
  join(directory, "migrations.ts"),
  [
    "// Generated by scripts/embed-migrations.ts from drizzle/. Do not edit.",
    'import type { MigrationMeta } from "drizzle-orm/migrator";',
    "",
    `export const migrations: readonly MigrationMeta[] = ${JSON.stringify(migrations, null, 2)};`,
    "",
  ].join("\n"),
);
